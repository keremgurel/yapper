/**
 * How a short script recreates a reference, shared by the first pass and the
 * short-form version writer.
 *
 * Written after a creator asked for "our own video, exactly the way this one
 * does it" from a 200-word App Store Connect reel and got 140 words, a hook
 * that changed the claim ("Apple quietly added two new images" for "Apple just
 * dropped a brand new feature... your app is already falling behind"), the
 * feature's name dropped, and the source creator's "day 4 of 5" read out as
 * if it were theirs.
 */
export const RECREATION_RULES =
  "- Length follows the material. With no reference transcript, aim for 80 " +
  "to 130 spoken words after the hook (about 35 to 55 seconds). With one, " +
  "match the reference's own spoken length, within about a fifth either way: " +
  "a longer reference earns a longer script, so never cut its points or " +
  "specifics to stay short.\n" +
  "- When recreating a reference, the first hook keeps the reference's own " +
  "opening: the same claim, the same stakes, as strong or stronger, said in " +
  "the creator's voice. Never soften, hedge, or reframe the claim (a feature " +
  "Apple 'just released' did not get 'quietly added'). The other hooks may " +
  "try different mechanisms.\n" +
  "- Keep the reference's names for things: the feature, setting, menu path, " +
  "or tool, exactly as it says them. A viewer must be able to find it.\n" +
  "- Keep the reference's order and the job each beat does (what changed, " +
  "where it is, why it matters, how to set it up, the urgency). Rewrite the " +
  "words, not the structure.\n" +
  "- Never copy the source creator's own framing into the creator's script: " +
  "their series markers ('day 4 of 5'), their follow asks, their name, or " +
  "their personal story, unless the creator's own words ask for it.\n";
