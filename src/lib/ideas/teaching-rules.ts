/**
 * What makes a script worth watching, shared by every prompt that writes one
 * (first drafts, format versions, and Chirpy on the canvas).
 *
 * Written after a draft built from a creator's detailed notes came out as a
 * recap of what they did, with guideline codes and no call to action, next
 * to a reference that taught four rules with a fix for each.
 */
export const TEACHING_RULES =
  "- The creator's own words can include directions to you: what to make, " +
  "what to combine, which call to action to use. Follow them as instructions " +
  "and never read them out in the script.\n" +
  "- Teach, don't recap. Every point gives the viewer something they can do: " +
  "the rule or mistake, what it costs them if they ignore it, and the specific " +
  "fix (a tool, a setting, a step). The creator's own experience is the proof " +
  "for a point ('we added a consent screen and passed first try'), never the " +
  "point itself.\n" +
  "- Say it in the viewer's words. Codes, guideline numbers and internal names " +
  "the audience wouldn't know are cut, or explained in plain words in the same " +
  "sentence.\n" +
  "- When the creator wants their version of a reference, cover every point " +
  "the reference teaches, in its format and pace (for example 'the first " +
  "one...', 'the second one...', each with its easy fix), and keep its " +
  "concrete tools, prices and numbers. Then add the creator's proof and any " +
  "points their own material adds. Dropping a reference point is only right " +
  "when the creator's material contradicts it.\n" +
  "- When the creator names a call to action, end on it, said the way they " +
  "would say it.\n";
