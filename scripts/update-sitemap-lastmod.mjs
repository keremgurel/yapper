// Writes src/lib/seo/sitemap-lastmod-generated.ts: one date per public route,
// taken from the last git commit that touched the files that render it.
//
// A committed file and not a build-time lookup, because Vercel builds from a
// shallow clone: `git log` there returns the deploy commit for every path,
// which is the "every URL changed today" signal search engines learn to
// ignore. Running this locally against full history gives a true date.
//
// Shared chrome (header, footer, buttons) is left out of each route's sources
// on purpose: a footer tweak does not make a page newer.
//
//   npm run seo:lastmod                 after committing page changes
//   npm run seo:lastmod -- --allow-dirty  while changes are still uncommitted;
//                                         a route with uncommitted source
//                                         changes gets today's date
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(import.meta.url), "../..");
const ROUTES = JSON.parse(
  readFileSync(resolve(ROOT, "src/lib/seo/public-routes.json"), "utf8"),
);
const OUT = resolve(ROOT, "src/lib/seo/sitemap-lastmod-generated.ts");
const allowDirty = process.argv.includes("--allow-dirty");
const today = new Date().toISOString().slice(0, 10);

const git = (...args) =>
  execFileSync("git", args, { cwd: ROOT, encoding: "utf8" }).trim();

export function lastmodFor(path, sources) {
  const dirty = git("status", "--porcelain", "--", ...sources);
  if (dirty) {
    if (allowDirty) return today;
    throw new Error(
      `${path} has uncommitted changes. Commit first, or pass --allow-dirty.`,
    );
  }
  const date = git("log", "-1", "--format=%cs", "--", ...sources);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date))
    throw new Error(`no git history for ${path}`);
  return date;
}

const dates = Object.fromEntries(
  Object.entries(ROUTES).map(([path, route]) => [
    path,
    lastmodFor(path, route.sources),
  ]),
);

writeFileSync(
  OUT,
  [
    "// Generated by scripts/update-sitemap-lastmod.mjs. Do not edit by hand;",
    "// run `npm run seo:lastmod` after committing page changes.",
    `export const SITEMAP_LASTMOD = ${JSON.stringify(dates, null, 2)} as const;`,
    "",
  ].join("\n"),
);
console.log(`wrote ${Object.keys(dates).length} routes to ${OUT}`);
