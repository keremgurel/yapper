"""The web contract types and the registry of server-runtime (Studio) actions."""
import json

from declarations import typescript_declarations

HEADER = "// Generated by scripts/app-actions/generate.py. Do not edit."


def typescript_contract(full):
    lines = [HEADER, "export type AppActionID = " + " | ".join(json.dumps(a["id"]) for a in full["x-actions"]) + ";", ""]
    return "\n".join(lines + typescript_declarations(full["$defs"]))


def studio_registry(full):
    """Server actions by ID with their input type names, for the Chirpy turn loop's executors."""
    server = [action for action in full["x-actions"] if action["runtime"] == "server"]
    inputs = sorted({action["input"] for action in server})
    lines = [HEADER, "// Server-runtime actions from protocol/actions; the Chirpy turn loop executes them.",
             "import type {", "  AppActionEffect,", *(f"  {name}," for name in inputs),
             '} from "../../../../protocol/app-actions.generated";', ""]
    if server:
        lines += ["export interface StudioActionInputs {"]
        lines += [f'  {json.dumps(action["id"])}: {action["input"]};' for action in server]
        lines += ["}"]
    else:
        lines += ["export type StudioActionInputs = Record<never, never>;"]
    lines += ["export type StudioActionID = keyof StudioActionInputs;", "",
              "export interface StudioActionDescriptor {", "  id: StudioActionID;", "  input: string;",
              "  effect: AppActionEffect;", "  confirm: boolean;", "}", "",
              "export const STUDIO_ACTIONS: readonly StudioActionDescriptor[] = ["]
    lines += [f'  {{ id: {json.dumps(a["id"])}, input: {json.dumps(a["input"])}, effect: {json.dumps(a["effect"])}, '
              f'confirm: {"true" if a.get("confirm") else "false"} }},' for a in server]
    lines += ["];", ""]
    return "\n".join(lines)
