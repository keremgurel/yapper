"""The native contract: action IDs, input types and the embedded client-only schema."""
import json

from declarations import swift_declarations


def swift_contract(client):
    lines = ["// Generated by scripts/app-actions/generate.py. Do not edit.", "import Foundation", "",
             "enum AppActionID: String, CaseIterable, Sendable {"]
    lines += [f'    case {action["symbol"]} = "{action["id"]}"' for action in client["x-actions"]]
    lines += ["}", ""]
    lines += swift_declarations(client["$defs"])
    for action in client["x-actions"]:
        lines += [f'extension {action["input"]}: AppActionInput {{',
                  f'    static var actionID: AppActionID {{ .{action["symbol"]} }}', "}", ""]
    lines += ["enum AppActionContract {", f'    static let version = {client["x-protocolVersion"]}',
              '    static let schemaJSON = #"""', json.dumps(client, separators=(",", ":")), '"""#', "}", ""]
    return "\n".join(lines)
