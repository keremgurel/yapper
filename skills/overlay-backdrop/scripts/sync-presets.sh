#!/bin/zsh
# Rebuilds render-preset.swift from the app's own preset code, so the skill and
# Yapper draw the same pixels. Run after changing anything in
# native-macos/Sources/YapperNative/Services/Backdrop/ or OverlayBackdrop.swift.
set -euo pipefail
here=${0:A:h}
app=${here:h:h:h}/native-macos/Sources/YapperNative
{
  print -r -- "// GENERATED by sync-presets.sh from the Yapper app sources. Do not edit by hand."
  print -r -- "// Usage: swift render-preset.swift <preset> <width> <height> <out.png> [focusX focusY]"
  print -r -- "import CoreGraphics"
  print -r -- "import Foundation"
  print -r -- "import ImageIO"
  print -r -- "import UniformTypeIdentifiers"
  for f in Models/Overlays/OverlayBackdrop.swift Services/Backdrop/BackdropShading.swift \
           Services/Backdrop/BackdropPresetShaders.swift Services/Backdrop/BackdropPresetRenderer.swift; do
    print -r -- ""
    print -r -- "// MARK: - $f"
    grep -v '^import ' "$app/$f"
  done
  cat "$here/render-preset-main.swift.in"
} > "$here/render-preset.swift"
print -r -- "$here/render-preset.swift"
